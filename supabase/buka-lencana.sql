sesi as (
  select r.n, r.hari,
         jsonb_build_object(
           'id', 'lencana-' || extract(epoch from now())::bigint || '-' || r.n,
           'date', to_char(r.hari, 'YYYY-MM-DD'),
           'subject', r.subject,
           'grade', t.grade,
           'results', (
             select jsonb_agg(jsonb_build_object('questionId', s.qid, 'topic', s.topic, 'correctFirstTry', true, 'solved', true, 'attempts', 1))
             from soal s where s.grade = t.grade and s.subject = r.subject
           )
         ) as isi
  from rencana r cross join target t
